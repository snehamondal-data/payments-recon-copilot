-- Snowflake setup for payments-recon-copilot (project-scale; trial account).
-- Run once in a Snowsight worksheet as ACCOUNTADMIN. Render the public keys in with:
--   python snowflake/render_setup.py   (writes secrets/setup_rendered.sql)
-- Safe to re-run: everything is CREATE ... IF NOT EXISTS or an idempotent GRANT/ALTER.

USE ROLE ACCOUNTADMIN;

-- 1. Cost guard: the trial can't run away. 10 credits a month is about 10 hours of XSMALL.
CREATE RESOURCE MONITOR IF NOT EXISTS RECON_MONITOR
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 90 PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS RECON_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE RECON_WH SET RESOURCE_MONITOR = RECON_MONITOR;

-- 2. Database and schemas. INTERMEDIATE is where dbt's intermediate models go (same layout as DuckDB).
CREATE DATABASE IF NOT EXISTS RECON;
CREATE SCHEMA IF NOT EXISTS RECON.RAW;
CREATE SCHEMA IF NOT EXISTS RECON.REF;
CREATE SCHEMA IF NOT EXISTS RECON.STAGING;
CREATE SCHEMA IF NOT EXISTS RECON.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS RECON.MARTS;
CREATE SCHEMA IF NOT EXISTS RECON.COPILOT;

-- 3. Roles. Both roll up to SYSADMIN so admins can see their objects.
CREATE ROLE IF NOT EXISTS RECON_LOADER_ROLE;
CREATE ROLE IF NOT EXISTS RECON_AGENT_ROLE;
GRANT ROLE RECON_LOADER_ROLE TO ROLE SYSADMIN;
GRANT ROLE RECON_AGENT_ROLE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE RECON_WH TO ROLE RECON_LOADER_ROLE;
GRANT USAGE ON WAREHOUSE RECON_WH TO ROLE RECON_AGENT_ROLE;
GRANT USAGE ON DATABASE RECON TO ROLE RECON_LOADER_ROLE;
GRANT USAGE ON DATABASE RECON TO ROLE RECON_AGENT_ROLE;

-- 4. Loader: writes RAW and REF, builds dbt models in STAGING, INTERMEDIATE and MARTS, writes COPILOT
--    (audit log and resolutions). It owns the objects it creates; it does not own the schemas.
GRANT USAGE, CREATE TABLE ON SCHEMA RECON.RAW TO ROLE RECON_LOADER_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA RECON.REF TO ROLE RECON_LOADER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA RECON.STAGING TO ROLE RECON_LOADER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA RECON.INTERMEDIATE TO ROLE RECON_LOADER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA RECON.MARTS TO ROLE RECON_LOADER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE SEQUENCE ON SCHEMA RECON.COPILOT TO ROLE RECON_LOADER_ROLE;

-- 5. Agent: SELECT only, on RAW, REF and MARTS. Nothing on COPILOT, STAGING or INTERMEDIATE.
--    Future grants cover tables the loader and dbt create (or re-create) later.
GRANT USAGE ON SCHEMA RECON.RAW TO ROLE RECON_AGENT_ROLE;
GRANT USAGE ON SCHEMA RECON.REF TO ROLE RECON_AGENT_ROLE;
GRANT USAGE ON SCHEMA RECON.MARTS TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RECON.RAW TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RECON.REF TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RECON.MARTS TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RECON.RAW TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RECON.REF TO ROLE RECON_AGENT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RECON.MARTS TO ROLE RECON_AGENT_ROLE;

-- 6. Service users: key-pair auth only (TYPE = SERVICE users cannot log in with a password).
CREATE USER IF NOT EXISTS RECON_LOADER
  TYPE = SERVICE DEFAULT_ROLE = RECON_LOADER_ROLE DEFAULT_WAREHOUSE = RECON_WH DEFAULT_NAMESPACE = RECON.RAW
  COMMENT = 'payments-recon-copilot loader, dbt and copilot audit writer';
ALTER USER RECON_LOADER SET RSA_PUBLIC_KEY = '{{RECON_LOADER_PUBLIC_KEY}}';
-- New users default to DEFAULT_SECONDARY_ROLES = ('ALL'). Off, so a session holds only its one role.
-- (The Python client also runs USE SECONDARY ROLES NONE on every connection.)
ALTER USER RECON_LOADER SET DEFAULT_SECONDARY_ROLES = ();
GRANT ROLE RECON_LOADER_ROLE TO USER RECON_LOADER;

CREATE USER IF NOT EXISTS RECON_AGENT
  TYPE = SERVICE DEFAULT_ROLE = RECON_AGENT_ROLE DEFAULT_WAREHOUSE = RECON_WH DEFAULT_NAMESPACE = RECON.MARTS
  COMMENT = 'payments-recon-copilot agent tools: read-only';
ALTER USER RECON_AGENT SET RSA_PUBLIC_KEY = '{{RECON_AGENT_PUBLIC_KEY}}';
ALTER USER RECON_AGENT SET DEFAULT_SECONDARY_ROLES = ();
GRANT ROLE RECON_AGENT_ROLE TO USER RECON_AGENT;

-- 7. Check: the agent role should list only USAGE and SELECT grants.
SHOW GRANTS TO ROLE RECON_AGENT_ROLE;
